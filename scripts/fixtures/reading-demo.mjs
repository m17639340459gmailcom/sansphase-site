import {makeCatalogDemo} from './catalog-data.mjs';

const outlines={
  notes:['从一条笔记开始','整理文章的结构','让图文保持清晰','发布之前再读一遍','下一次继续记录'],
  works:['这个作品解决什么问题','功能与使用流程','界面与细节展示','当前限制与取舍','后续计划'],
  resources:['这份资料可以用来做什么','资料结构与使用顺序','示例与阅读方式','整理时需要注意的事项','来源与使用说明'],
  software:['软件的用途与适用人群','安装与第一次使用','日常使用的几个细节','适用场景与限制','官方来源与下一步'],
  'resource-center':['资源说明','内容组成与获取方式','查看资源的正确顺序','使用范围与注意事项','后续整理计划'],
};
function body(kind){
  const headings=outlines[kind];
  const hasSidebar=['notes','resources','resource-center'].includes(kind);
  return `<p class="article-preview-label">本地排版演示 · 以下文字用于体验目录与分享，不是正式发布内容。</p>
    <h2>${headings[0]}</h2>
    <p>一份内容是否好读，往往取决于读者能不能很快找到自己关心的部分。先说明用途，再讲具体过程，最后交代限制，能让第一次打开页面的人知道从哪里开始。</p>
    <p>${hasSidebar?'电脑端的左栏保留作者资料、音乐和独立的文章目录。你可以从头向下阅读，也可以在左侧直接跳到某一节；目录会标出当前阅读的章节。':'这个示例保留了完整的阅读顺序。你可以从头向下阅读，也可以展开正文前的文章目录，跳到某一节。滑过目录后，导航栏下方会出现一个小 V 入口，点击才展开阅读导航。'}</p>
    <h2>${headings[1]}</h2>
    <p>把信息按实际使用顺序排列，会比一次堆出所有细节更容易理解。先建立整体印象，再拆分步骤；需要反复查找的信息，则使用更明确的小标题。</p>
    <h3>先确认用途，再开始操作</h3>
    <p>打开一份资料或介绍时，先看它想解决的问题、需要准备什么，以及最后能得到什么结果。涉及安装、下载或设置时，把前提条件放在步骤之前。</p>
    <ul><li>用摘要说明主要用途，不重复标题。</li><li>把必要的准备事项放在前面。</li><li>完成一个步骤后，再进入下一步。</li></ul>
    <h3>为后续检索保留清楚的标题与分类</h3>
    <p>“安装与第一次使用”比“其他内容”更容易判断是否需要阅读。较长的标题会在目录中自然换行；小节向内缩进，方便分辨它属于哪个大章节。</p>
    <blockquote><p>标题负责告诉读者这一节讲什么，正文负责把事情解释清楚。两者各自做好自己的工作，阅读会更轻松。</p></blockquote>
    <h2>${headings[2]}</h2>
    <p>在需要展示实际效果的位置放图，并紧接着解释图中值得注意的部分。不要让读者在很长一段文字与遥远的图片之间来回寻找对应关系。</p>
    <p>这里用一张站内已有的星空素材演示正文图片的排版。它仅用于本地布局预览，不代表软件界面、作品成果或资源内容。</p>
    <img src="./assets/materials/eso-orion.jpg" width="1280" height="720" alt="本地排版示例：猎户座星空素材" loading="lazy">
    <h3>在不同设备上继续阅读</h3>
    <p>${hasSidebar?'电脑端阅读时，左侧目录会停留在导航栏下方。手机端依次显示个人资料、音乐和文章，目录收在正文前，可点击展开。滑过手机端的目录后，小 V 入口仍可带你回到目录，或直达文章底部。':'文章目录保持在正文前，电脑和手机都可以点击展开。滑过目录后，可点击导航栏下方的小 V 入口，向下拉出“回到目录 · 到达底部”。前者返回并展开目录，后者直达这篇文章的底部；抽屉默认收起，不会因悬停而展开。'}</p>
    <h2>${headings[3]}</h2>
    <p>记录里应该区分已经确认的结果、自己的使用感受，以及还没有验证的部分。不要用排版上的完整，代替信息本身的准确。</p>
    <ol><li>检查正文顺序是否清楚，标题能否概括对应内容。</li><li>确认图片与文字互相对应，读者不需要猜测含义。</li><li>检查链接是否指向预期位置，附件是否有必要的说明。</li></ol>
    <p>这份本地示例中的分享按钮会分享当前预览页面。在正式网站上，它才会对应正式文章地址。本地内容不会自动写入线上网站。</p>
    <h2>${headings[4]}</h2>
    <p>保持一次只说清楚一个主题。后续增加信息时，把内容放回合适的章节，让原有的阅读顺序仍然成立，而不是不断追加到页面末尾。</p>
    <p>读完后，可以通过下方的“分享”复制链接，也可以选择“浏览更多”返回当前栏目。两个入口统一放在右侧，用一个间隔点分开。</p>`;
}
