import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import postcss from 'postcss';
import sharp from 'sharp';
import { createCommunityConsolePreview } from '../scripts/preview-community-console.ts';
import { communityStaffArtSource } from '../src/community-staff-art.ts';
import { communityVipFrameSource } from '../src/community-vip-frame.ts';

type ArtworkFile = { file: string };

test('a freshly built original-management preview serves every approved staff, level, badge and VIP artwork', { timeout: 180000 }, async t => {
  // One complete independent build exercises the actual preview boundary;
  // permission-only tests continue to use the inexpensive buildAssets:false.
  const preview = await createCommunityConsolePreview();
  t.after(preview.close);
  const paths = new Set<string>();
  const staff = JSON.parse(await readFile('public/assets/community/staff/sources.json', 'utf8')) as { icons: ArtworkFile[]; frames: ArtworkFile[] };
  const levels = JSON.parse(await readFile('public/assets/community/levels/sources.json', 'utf8')) as { icons: ArtworkFile[]; trustIcons: ArtworkFile[]; vipIcons: ArtworkFile[] };
  assert.ok(staff.icons.length && staff.frames.length && levels.icons.length && levels.trustIcons.length && levels.vipIcons.length);
  for (const item of [...staff.icons, ...staff.frames]) {
    assert.match(item.file, /\.svg$/);
    for (const compact of [false, true]) {
      const source = communityStaffArtSource(item.file.slice(0, -4), compact);
      assert.ok(source, `the public staff renderer must recognize ${item.file}`);
      paths.add(source);
    }
  }
  for (const item of [...levels.icons, ...levels.trustIcons, ...levels.vipIcons]) {
    assert.match(item.file, /\.svg$/);
    paths.add(`/assets/community/levels/${item.file}`);
    paths.add(`/assets/community/levels/compact/${item.file.slice(0, -4)}.webp`);
  }
  for (const compact of [false, true]) paths.add(communityVipFrameSource(compact));

  const stylesheet = await fetch(`${preview.origin}/community.css`);
  assert.equal(stylesheet.status, 200);
  const atlasPaths = new Set<string>();
  postcss.parse(await stylesheet.text()).walkDecls(/^(?:background-image|mask-image)$/, declaration => {
    // Read the shipped stylesheet's actual fixed artwork references rather
    // than maintaining a separate list of badge image files in this test.
    for (const match of declaration.value.matchAll(/url\(\s*(['"]?)([^'"()]+)\1\s*\)/g)) {
      const source = new URL(match[2], `${preview.origin}/community.css`);
      if (source.origin === preview.origin && source.pathname.startsWith('/assets/community/badges/')) atlasPaths.add(source.pathname);
    }
  });
  assert.ok(atlasPaths.size, 'the real community stylesheet must reference its badge atlas');
  for (const source of atlasPaths) paths.add(source);
  for (const source of paths) {
    const response = await fetch(`${preview.origin}${source}`);
    assert.equal(response.status, 200, `missing preview artwork: ${source}`);
    assert.match(response.headers.get('content-type') || '', /^image\//, source);
    const bytes = Buffer.from(await response.arrayBuffer());
    const metadata = await sharp(bytes).metadata();
    assert.ok(metadata.width && metadata.height, `preview image is not decodable: ${source}`);
    const path = new URL(source, preview.origin).pathname.slice(1);
    assert.deepEqual(bytes, await readFile(resolve(preview.publicDirectory, path)), `HTTP must serve the generated bytes: ${source}`);
  }
  t.diagnostic(`Verified ${paths.size} current manifest/helper/CSS artwork URLs from one isolated preview build.`);
});
